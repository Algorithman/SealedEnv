using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SealedEnv.Generators;

/// <summary>
///     Renders the generated partial type with Load/TryLoad/SealedEnvBind.
///     Thin on purpose: every parse decision lives in the runtime
///     <see cref="SealedEnvLoader" /> helpers, so generated code is one call per member.
///     All references are global::-qualified and the output is a file-scoped namespace,
///     so nothing collides with user code or ambient usings.
/// </summary>
internal static class SealedEnvEmitter
{
    public static string Emit(EnvTargetModel target, string generatorVersion)
    {
        var builder = new StringBuilder(4096);
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("//     Generated by SealedEnvGenerator. Do not edit.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        if (target.Namespace is { Length: > 0, } @namespace)
        {
            builder.AppendLine($"namespace {@namespace};");
            builder.AppendLine();
        }

        builder.AppendLine($"{target.TypeDeclaration} {target.TypeName}");
        builder.AppendLine("{");

        if (target.PropertyMode)
        {
            EmitPropertyInfrastructure(builder, target, generatorVersion);
            builder.AppendLine();
        }

        EmitLoad(builder, target, generatorVersion);
        builder.AppendLine();
        EmitTryLoad(builder, target, generatorVersion);
        builder.AppendLine();
        EmitBind(builder, target, generatorVersion);

        if (target.GenerateDocumentation)
        {
            builder.AppendLine();
            EmitDocumentationMember(builder, target, generatorVersion);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>
    ///     The markdown table as a carrier member, so applications can render their
    ///     own configuration help at runtime (CLI --help-config style) without
    ///     touching the generated file.
    /// </summary>
    private static void EmitDocumentationMember(StringBuilder builder, EnvTargetModel target, string generatorVersion)
    {
        builder.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"SealedEnvGenerator\", \"{generatorVersion}\")]");
        builder.AppendLine("    public const string ConfigurationDocumentation =");
        builder.AppendLine($"        \"{EscapedBody(EmitDocumentation(target).TrimEnd())}\";");
    }

    /// <summary>
    ///     Property-mode infrastructure for the [EnvKey] partial properties: the
    ///     private readonly backing fields, the implementing declarations (expression-
    ///     bodied get over the field), and the constructor Load builds the carrier
    ///     through. Readonly value-type carriers work because the fields are readonly
    ///     and assigned from the constructor only.
    /// </summary>
    private static void EmitPropertyInfrastructure(StringBuilder builder, EnvTargetModel target, string generatorVersion)
    {
        var generatedCode = $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"SealedEnvGenerator\", \"{generatorVersion}\")]";

        foreach (var member in target.Members)
        {
            builder.AppendLine($"    private readonly {member.AnnotatedTypeText} {member.VariableName};");
        }

        if (target.Members.Length > 0)
        {
            builder.AppendLine();
        }

        foreach (var member in target.Members)
        {
            builder.AppendLine($"    {generatedCode}");
            builder.AppendLine(
                $"    {member.AccessibilityText} partial {member.AnnotatedTypeText} {Identifier(member.ParameterName)}");
            builder.AppendLine("    {");
            builder.AppendLine($"        get => {member.VariableName};");
            builder.AppendLine("    }");
        }

        if (target.Members.Length > 0)
        {
            builder.AppendLine();
        }

        builder.AppendLine($"    {generatedCode}");
        builder.AppendLine(
            $"    {target.TypeAccessibility} {target.TypeName}({ConstructorParameters(target.Members)})");
        builder.AppendLine("    {");
        for (var index = 0; index < target.Members.Length; index++)
        {
            // Assign the backing FIELD, not the property: the implementing accessor is
            // get-only with an explicit body, and only auto-implemented properties are
            // constructor-assignable. Positionally mangled parameters (__p0, __p1, ...)
            // keep two members whose names differ only by case ("Port" / "port") apart.
            builder.AppendLine($"        {target.Members[index].VariableName} = __p{index};");
        }

        builder.AppendLine("    }");
    }

    private static string ConstructorParameters(ImmutableArray<EnvMemberModel> members)
    {
        return string.Join(", ", members.Select((member, index) => $"{member.AnnotatedTypeText} __p{index}"));
    }

    /// <summary>
    ///     C# keyword names (@class and friends) must be emitted escaped — the symbol
    ///     name carries no '@'.
    /// </summary>
    private static string Identifier(string name)
    {
        return SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
    }

    public static string HintName(EnvTargetModel target)
    {
        return target.Namespace is { Length: > 0, } @namespace
            ? $"{@namespace}.{target.TypeName}.SealedEnv.g.cs"
            : $"{target.TypeName}.SealedEnv.g.cs";
    }

    /// <summary>
    ///     The markdown documentation table (Key / Type / Required / Default /
    ///     Description), emitted as the carrier's <c>ConfigurationDocumentation</c>
    ///     member when the type opts in via GenerateDocumentation. AddSource can only
    ///     produce C# files, so the table ships as a string member — pipelines can
    ///     dump it to a file with a few lines of code.
    /// </summary>
    public static string EmitDocumentation(EnvTargetModel target)
    {
        var builder = new StringBuilder(1024);
        builder.AppendLine("<!-- Generated by SealedEnvGenerator. Do not edit. -->");
        builder.AppendLine();
        builder.AppendLine("| Key | Type | Required | Default | Description |");
        builder.AppendLine("|-----|------|----------|---------|-------------|");
        foreach (var member in target.Members)
        {
            var key = Md(member.Key);
            var type = Md(FriendlyType(member.TypeText));
            var required = member.Required ? "Yes" : "No";
            var @default = member.Default is null ? "—" : $"`{Md(member.Default)}`";
            var description = Md(member.Description ?? string.Empty);
            builder.AppendLine($"| `{key}` | `{type}` | {required} | {@default} | {description} |");
        }

        // AppendLine uses Environment.NewLine — normalize to LF so the emitted
        // member is byte-identical on Windows and Unix.
        return builder.ToString().Replace("\r\n", "\n");

        static string Md(string value)
        {
            return value
                .Replace("|", "\\|")
                .Replace("\r", " ")
                .Replace("\n", " ");
        }

        /// <summary>global::-qualified display text to a docs-friendly simple name.</summary>
        static string FriendlyType(string typeText)
        {
            var text = typeText.Replace("global::", string.Empty);
            var lastDot = text.LastIndexOf('.');
            return lastDot >= 0 ? text.Substring(lastDot + 1) : text;
        }
    }

    private static void EmitLoad(StringBuilder builder, EnvTargetModel target, string generatorVersion)
    {
        builder.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"SealedEnvGenerator\", \"{generatorVersion}\")]");
        builder.AppendLine($"    public static {target.TypeName} Load(global::SealedEnv.IEnvProvider? provider = null)");
        builder.AppendLine("    {");
        builder.AppendLine("        var bound = SealedEnvBind(provider ?? global::SealedEnv.EnvironmentEnvProvider.Instance, out var __errors);");
        builder.AppendLine("        if (bound is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            throw new global::SealedEnv.SealedEnvException(__errors);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine(target.IsValueType ? "        return bound.Value;" : "        return bound;");
        builder.AppendLine("    }");
    }

    private static void EmitTryLoad(StringBuilder builder, EnvTargetModel target, string generatorVersion)
    {
        var nullableConfig = target.IsValueType ? target.TypeName : target.TypeName + "?";
        builder.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"SealedEnvGenerator\", \"{generatorVersion}\")]");
        builder.AppendLine(
            $"    public static bool TryLoad(out {nullableConfig} config, out global::System.Collections.Generic.IReadOnlyList<global::SealedEnv.EnvError> errors, global::SealedEnv.IEnvProvider? provider = null)");
        builder.AppendLine("    {");
        builder.AppendLine("        var bound = SealedEnvBind(provider ?? global::SealedEnv.EnvironmentEnvProvider.Instance, out var __errors);");
        builder.AppendLine("        errors = __errors;");
        builder.AppendLine(target.IsValueType
            ? "        config = bound.GetValueOrDefault();"
            : "        config = bound;");
        builder.AppendLine("        return bound is not null;");
        builder.AppendLine("    }");
    }

    private static void EmitBind(StringBuilder builder, EnvTargetModel target, string generatorVersion)
    {
        builder.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"SealedEnvGenerator\", \"{generatorVersion}\")]");
        builder.AppendLine(
            $"    private static {target.TypeName}? SealedEnvBind(global::SealedEnv.IEnvProvider provider, out global::System.Collections.Generic.List<global::SealedEnv.EnvError> __errors)");
        builder.AppendLine("    {");
        builder.AppendLine("        __errors = new global::System.Collections.Generic.List<global::SealedEnv.EnvError>();");
        builder.AppendLine();

        var displayName = $"{target.TypeName}.";
        foreach (var member in target.Members)
        {
            builder.AppendLine(
                $"        {member.LocalTypeText} {member.VariableName} = {HelperCall(target, member, displayName)};");
            builder.AppendLine();
        }

        builder.AppendLine("        if (__errors.Count > 0)");
        builder.AppendLine("        {");
        builder.AppendLine("            return null;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine($"        return new {target.TypeName}({ConstructorArguments(target.Members)});");
        builder.AppendLine("    }");
    }

    private static string HelperCall(EnvTargetModel target, EnvMemberModel member, string displayNamePrefix)
    {
        // List members target the same runtime rule with the "Array" suffix
        // (String → StringArray, Enum → EnumArray, Custom → CustomArray): the
        // element parsing is the scalar rule, applied per entry.
        var helperName = member.Kind switch
        {
            MemberKind.Int => "Int",
            MemberKind.Long => "Long",
            MemberKind.Double => "Double",
            MemberKind.Bool => "Bool",
            MemberKind.String => "String",
            MemberKind.NullableString => "NullableString",
            MemberKind.TimeSpan => "TimeSpan",
            MemberKind.Uri => "Uri",
            MemberKind.Guid => "Guid",
            MemberKind.Enum => "Enum",
            MemberKind.Parsable => "Parsable",
            MemberKind.Custom => "Custom",
            _ => throw new InvalidOperationException($"Unknown member kind: {member.Kind}"),
        };

        if (member.IsArray)
        {
            helperName += "Array";
        }

        // Generic helpers take the ELEMENT type for lists (EnumArray<LogLevel>) and
        // the member type for scalars (Custom<VatRate>).
        var isGeneric = member.Kind is MemberKind.Enum or MemberKind.Parsable or MemberKind.Custom;
        var genericText = isGeneric ? (member.IsArray ? member.ElementTypeText : member.TypeText) : string.Empty;

        return $"global::SealedEnv.SealedEnvLoader.{helperName}{(isGeneric ? $"<{genericText}>" : string.Empty)}({Args(target, member, displayNamePrefix)})";
    }

    private static string Args(EnvTargetModel target, EnvMemberModel member, string displayNamePrefix)
    {
        var args = new StringBuilder(256);
        args.Append("provider, ");
        args.Append(Literal(member.Key)).Append(", ");
        args.Append(Literal(displayNamePrefix + member.ParameterName)).Append(", ");
        args.Append(member.Default is null ? "null" : Literal(member.Default)).Append(", ");
        args.Append(member.Required ? "true" : "false").Append(", ");
        args.Append(member.AllowEmpty ? "true" : "false").Append(", ");
        args.Append(target.EmptyAsUnset ? "true" : "false");

        // Whole-value custom parser sits before ref; list members take the separator
        // (StringArray position), and a per-entry custom parser trails it
        // (CustomArray(provider, ..., separator, parse, ref errors)).
        if (member.Kind == MemberKind.Custom && !member.IsArray)
        {
            args.Append(", ").Append(member.ParserText).Append(".Parse");
        }

        if (member.IsArray)
        {
            args.Append(", ").Append(CharLiteral(member.Separator));
        }

        if (member.Kind == MemberKind.Custom && member.IsArray)
        {
            args.Append(", ").Append(member.ParserText).Append(".Parse");
        }

        args.Append(", ref __errors");
        return args.ToString();
    }

    private static string ConstructorArguments(ImmutableArray<EnvMemberModel> members)
    {
        return string.Join(", ", members.Select(m => m.PassWithNullForgiving ? m.VariableName + "!" : m.VariableName));
    }

    /// <summary>String literals are escaped by Roslyn itself — keys and defaults can contain anything.</summary>
    private static string Literal(string value)
    {
        return SymbolDisplay.FormatLiteral(value, true);
    }

    /// <summary>
    ///     The escaped body of a string literal WITHOUT the surrounding quotes —
    ///     for emitting into an already-quoted position. FormatLiteral(quote: true)
    ///     wraps and escapes; slicing its outer quotes keeps every inner escape
    ///     (including embedded quotes as \").
    /// </summary>
    private static string EscapedBody(string value)
    {
        var quoted = SymbolDisplay.FormatLiteral(value, true);
        return quoted.Substring(1, quoted.Length - 2);
    }

    private static string CharLiteral(char value)
    {
        return SymbolDisplay.FormatLiteral(value, true);
    }
}
